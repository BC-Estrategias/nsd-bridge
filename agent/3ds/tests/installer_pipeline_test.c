static Result FSFILE_Write(Handle h, u32 *wrote, uint64_t off, const void *buf, u32 n, u32 flags) {
  (void)h; (void)flags;
  g_calls++;
  if (g_write_delay_us) usleep((useconds_t)g_write_delay_us);
  if (g_fail_at_call >= 0 && g_calls == g_fail_at_call + 1) { *wrote = 0; return -1; }
  assert(off == g_out_len && "writes must arrive in order, with no gaps");
  assert(g_out_len + n <= g_out_cap);
  memcpy(g_out + off, buf, n);
  g_out_len += n;
  *wrote = n;
  return 0;
}
