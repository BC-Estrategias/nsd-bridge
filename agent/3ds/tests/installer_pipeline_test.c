/* ---- the tests ---- */
static void fill(uint8_t *p, size_t n, unsigned seed) { size_t i; for (i = 0; i < n; i++) { seed = seed * 1103515245u + 12345u; p[i] = (uint8_t)(seed >> 16); } }

/* feeds `total` bytes in pieces of random sizes (like a download), optionally sleeping, then finishes */
static bool run(size_t total, int producer_delay_us, int abort_after_bytes, uint8_t *src) {
  sink k; cia_info ci = {0, 0x000400000BD00200ull, total, 0};
  size_t pos = 0; bool ok = true; unsigned r = 7;
  memset(&k, 0, sizeof k);
  g_out_len = 0; g_calls = 0; g_fail_code = 0; g_cancelled_am = 0;
  if (!sink_open(&k, &ci, 0)) return false;
  while (pos < total) {
    size_t n; r = r * 1664525u + 1013904223u; n = 1 + (r >> 8) % 20000;
    if (pos + n > total) n = total - pos;
    if (producer_delay_us) usleep((useconds_t)producer_delay_us);
    if (!sink_write(&k, src + pos, n, total)) { ok = false; break; }
    pos += n;
    if (abort_after_bytes >= 0 && (int)pos >= abort_after_bytes) { sink_abort(&k); return false; }
  }
  if (!ok) { sink_abort(&k); fail(INS_E_AM, k.res); return false; } /* what installer.c does after a failed write */
  return sink_finish(&k, &ci);
}

int main(void) {
  alarm(90); /* a deadlock shows up as a killed test, not a hang */
  size_t total = 6u * 1024 * 1024 + 12345;
  uint8_t *src = malloc(total), want[32];
  size_t sizes[] = {1, 1000, BLOCK - 1, BLOCK, BLOCK + 1, 5 * BLOCK, 7 * BLOCK + 3, total};
  size_t i;
  g_out_cap = total + 1024; g_out = malloc(g_out_cap);
  fill(src, total, 1);

  /* every size, fast and slow writers, slow producer: the bytes arrive complete and in order, the hash is right */
  for (i = 0; i < sizeof sizes / sizeof sizes[0]; i++) {
    int wd, pd;
    for (wd = 0; wd <= 300; wd += 300)
      for (pd = 0; pd <= 50; pd += 50) {
        g_write_delay_us = wd; g_fail_at_call = -1;
        g_have_expect = true;
        ndp_sha256(src, sizes[i], want); memcpy(g_expect, want, 32);
        assert(run(sizes[i], pd, -1, src) && "a clean run succeeds");
        assert(g_out_len == sizes[i] && memcmp(g_out, src, sizes[i]) == 0);
        assert(g_progress_last == sizes[i]);
      }
  }
  /* a wrong expected hash installs nothing (AM_Finish is never reached: the install is cancelled) */
  g_write_delay_us = 0; g_have_expect = true; memset(g_expect, 0xAA, 32);
  assert(!run(3 * BLOCK + 5, 0, -1, src) && g_fail_code == INS_E_HASH && g_cancelled_am == 1);
  g_have_expect = false;
  /* a write that fails in the middle: reported, no deadlock, the producer is released */
  for (i = 0; i < 6; i++) {
    g_fail_at_call = (int)i; g_write_delay_us = 200;
    assert(!run(10 * BLOCK, 0, -1, src) && g_fail_code == INS_E_AM && g_cancelled_am == 1);
  }
  g_fail_at_call = -1;
  /* an abort (cancel) at various points, with a slow writer so slots are queued: no deadlock, AM cancelled once */
  for (i = 0; i < 8; i++) {
    g_write_delay_us = 500;
    assert(!run(12 * BLOCK, 0, (int)(i * BLOCK + 17), src) && g_cancelled_am == 1);
  }
  /* the size check: handing over fewer bytes than the header says */
  {
    sink k; cia_info ci = {0, 1, 5 * BLOCK, 0};
    memset(&k, 0, sizeof k); g_write_delay_us = 0; g_have_expect = false; g_out_len = 0; g_cancelled_am = 0;
    assert(sink_open(&k, &ci, 0));
    assert(sink_write(&k, src, 3 * BLOCK, ci.total_size));
    assert(!sink_finish(&k, &ci) && g_fail_code == INS_E_SIZE && g_cancelled_am == 1);
  }
  assert(g_seed_calls > 0 && "a successful install asks for the seed");
  puts("installer pipeline: all ok");
  return 0;
}
